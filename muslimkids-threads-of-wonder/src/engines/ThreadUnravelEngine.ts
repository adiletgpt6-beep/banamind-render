// ThreadUnravelEngine — контролируемое расплетение тканой Земли.
// Не взрыв частиц: сначала из переплетения выходит одна нить (северная параллель),
// затем соседние; каждая нить сохраняет непрерывность — её свободный конец (шов
// кольца) отходит первым, а точки нити по очереди «отклеиваются» бегущим фронтом,
// поднимаются над поверхностью (провисание по нормали от центра) и плавно натягиваются
// вдоль новой формы — рядов горной диорамы. Меридианы следуют позже и с другого конца.
import { EARTH } from "../scenes/Scene02Earth";

export const UNRAVEL = {
  dur: 42, // переход одной точки, кадры
  spread: 34, // пробег фронта вдоль нити, кадры
  liftRing: 0.75, // высота «вытягивания» параллели
  liftMer: 0.55,
};

export const unravelStart = {
  /** Параллели — с севера на юг: первая нить выходит на 432-м кадре (00:14.4). */
  ring: (i: number) => 432 + (EARTH.NR - 1 - i) * 1.5,
  /** Меридианы — от центра видимой стороны к краям. */
  mer: (j: number) => 450 + Math.abs(j - (EARTH.NM - 1) / 2) * 1.15,
  cap: (c: number) => 470 + c * 8,
  cloud: (c: number) => 462 + c * 3,
};
