// SOURCE_MAP.md фильма BM-005: каждая сцена → страницы PDF и закон приложенного TXT,
// что именно взято из книги; плюс повреждённые страницы, OCR-исправления и оговорки.
// Запуск: node scripts/lesson-greene/source-map.mjs [books/robert-greene-48-laws-of-power/SOURCE_MAP.md]
import { writeFileSync } from "node:fs";
import { SCENES, loadManifest, timeline } from "./lib.mjs";

const OUT = process.argv[2] ?? "books/robert-greene-48-laws-of-power/SOURCE_MAP.md";
const tl = timeline();
const voiced = Boolean(loadManifest()?.lines?.length);
const mmss = (s) => `${String(Math.floor(s / 60)).padStart(2, "0")}:${String(Math.floor(s % 60)).padStart(2, "0")}`;

// какие законы реально использованы (по ссылкам сцен)
const laws = new Map();
SCENES.forEach((s) =>
  s.src.forEach((r) => {
    const m = /\(закон (\d+)\)/.exec(r);
    if (m) laws.set(Number(m[1]), [...(laws.get(Number(m[1])) ?? []), s.id]);
  }),
);
const pages = SCENES.flatMap((s) => s.src.map((r) => /^PDF (\d+)(?:–(\d+))?/.exec(r)).map((m) => [Number(m[1]), Number(m[2] ?? m[1])]));
const touchesDamaged = pages.some(([a, b]) => !(b < 137 || a > 151));

const md = [];
md.push("# SOURCE_MAP — BM-005 · Роберт Грин, «48 законов власти»", "");
md.push("Источник: приложенный владельцем TXT `robert_grin_48_zakonov_vlasti_full_text.txt` (2 314 273 байта, 18 587 строк,");
md.push("SHA256 `30d75837d113b6b4bd6c880d07c89727ea19ae23580891b311e3fc1860845577`), извлечённый из PDF русского издания");
md.push("(РИПОЛ КЛАССИК, Москва, 2003; пер. с англ. Е. Я. Мигуновой; © Robert Greene, 1998). Страницы — номера маркеров");
md.push("`СТРАНИЦА PDF N / 390` (не печатные номера). Подробные конспекты всей книги: `research/notes-part1..5.md`.", "");
md.push("## Повреждённые страницы", "");
md.push("PDF **137–151** в исходнике заменены маркерами «СТРАНИЦА ПОВРЕЖДЕНА…». По оглавлению там законы 20 («Ни с кем не объединяйся»)");
md.push("и 21 («Прикинься простаком…»), а также начало закона 22 до PDF 152. В фильме эти законы только названы как пропущенные");
md.push(`(сцена 4); ни одна сцена не ссылается на страницы 137–151 — проверено автоматически: ${touchesDamaged ? "**ОШИБКА — есть ссылки**" : "ссылок нет ✓"}`);
md.push("(тест `повреждённые страницы PDF 137–151 не используются` в `scripts/lesson-greene/script.test.mjs`). Содержание по памяти,");
md.push("другим изданиям или интернету не восстанавливалось.", "");
md.push(`## Сцены фильма → страницы`, "");
md.push(`Таймкоды — время в фильме${voiced ? " (по реальной озвучке)" : " (черновые, до озвучки)"}. Формулировки фильма — свои; дословных`);
md.push("фрагментов перевода нет, кроме коротких реплик персонажей (до ~10 слов).", "");
md.push("| Время | Сцена | Страницы PDF (закон) | Что взято из книги |", "|---|---|---|---|");
SCENES.forEach((s, i) => {
  md.push(`| ${mmss(tl.scenes[i].from)} | ${i + 1}. ${s.title} | ${s.src.join("; ")} | ${(s.srcNote ?? "").replace(/\|/g, "/")} |`);
});
md.push("");
md.push(`## Использованные законы (${laws.size} из 48)`, "");
[...laws.keys()].sort((a, b) => a - b).forEach((n) => md.push(`- закон ${n}: сцены ${[...new Set(laws.get(n))].join(", ")}`));
md.push("");
md.push("## Имена и OCR (так в TXT → как в фильме)", "");
md.push("- «Чуко Лан» (PDF 50–51) и «Чжугэ Лян» (PDF 335–336) — оставлены так, как написаны в соответствующих главах перевода; в фильме не утверждается, что это одно лицо.");
md.push("- «Ми Цуся» (PDF 53–54), «Итакура … Шигемуне» (PDF 294), «Миньюэ» (PDF 335), «Педрариас» (PDF 216) — как в тексте.");
md.push("- «Аль Каноне» (PDF 91, OCR) → Аль Капоне (на той же странице дальше «Капоне»).");
md.push("- Систематическая замена OCR «ц» → «и» (гериог = герцог, иена = цена, сиена = сцена) исправлена при чтении; на смысл фактов не влияет.");
md.push("");
md.push("## Позиция автора и выводы BanaMind", "");
md.push("- Тезисы «власть поневоле аморальна» (PDF 19), «мир — гигантский двор» (PDF 15–17), советы изображать наивность (PDF 24), раскачивать");
md.push("  чужие эмоции (PDF 298), «преданных легче обманывать» (PDF 338) в фильме названы позицией автора.");
md.push("- Оценки «здоровая версия совета», «Фуше — приспособленец», памятка «5 признаков манипуляции», «вопрос: кому выгоден слух»,");
md.push("  «менять форму, а не ценности» и финальный вывод — собственные выводы BanaMind, помечены в `srcNote` сцен.");
md.push("- Исторические истории даны как истории и толкования книги; где у автора спорные датировки (например, «монголы заняли Китай в XII веке»,");
md.push("  PDF 99) — эти детали в фильм не взяты.");
md.push("");
md.push("## Что сознательно не вошло", "");
md.push("См. `BRIEF.md`, раздел «Что намеренно опущено».", "");
writeFileSync(OUT, md.join("\n"));
console.log(`✓ ${OUT}: ${SCENES.length} сцен, законов ${laws.size}`);
