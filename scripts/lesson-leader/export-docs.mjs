const lineNums = (r) => {
  const out = [];
  for (const m of r.matchAll(/(\d{2,4})(?:–(\d{2,4}))?/g)) {
    const a = Number(m[1]);
    const b = m[2] ? Number(m[2]) : a;
    if (b - a > 40) out.push(a, b);
    else for (let n = a; n <= b; n++) if (book?.[n - 1]?.trim() && book[n - 1].trim() !== "...") out.push(n);
  }
  return [...new Set(out)].slice(0, 8);
};
