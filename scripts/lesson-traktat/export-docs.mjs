// ── сценарий ──
const sc = [];
sc.push(`# ${LESSON.title}`, "");
sc.push(`2D-анимационное объяснение книги ${LESSON.book} для широкой аудитории (подростки, взрослые, дети). Ведущий — банан, обращение к зрителю на «вы».`);
sc.push(`Длительность по озвучке: **${mmss(tl.duration)}** (речь без растяжки пауз — ${mmss(tl.natural)}). Голос: ${VOICE.name}, темп ${VOICE.settings.speed}.`);
sc.push("Формат: 1920×1080, 30 fps. Без музыки; в конце паузы-вопроса — тихий мягкий сигнал.", "");
sc.push("Источник — только прикреплённая аудиокнига; интервалы — в `source_map.md`. Таймкоды ниже — время в фильме.", "");
let words = 0;
let qn = 0;
tl.scenes.forEach((ts, i) => {
  const s = SCENES[i];
  sc.push(`## ${mmss(ts.from)} · Сцена ${i + 1}. ${s.title}`, "");
  sc.push(`*Часть:* ${PART[s.part]} · *Кадр:* ${HOST[s.host]} · *Схема:* ${VIS[s.visual.kind] ?? s.visual.kind}`, "");
  ts.lines.forEach((ln, j) => {
    const l = s.lines[j];
    words += l.text.split(/\s+/).length;
    const act = [POSE_RU[l.pose], MOOD_RU[l.mood]].filter(Boolean).join(", ");
    sc.push(`- **${mmss(ln.speechFrom)}** ${l.text}${act ? `  _(банан: ${act})_` : ""}`);
    if (ln.waitFrom !== undefined) {
      qn++;
      sc.push(`- **${mmss(ln.waitFrom)}** ⏸ *Вопрос ${qn}: пауза ${l.wait} с на размышление: на экране — карточка с вопросом (без таймера).*`);
    }
  });
  sc.push("");
});
sc.push(`---`, "", `Всего сцен: ${tl.scenes.length}, реплик: ${tl.lines.length}, слов: ${words}, интерактивных вопросов: ${qn}.`, "");
writeFileSync(`${DIR}/lesson_30min_script.md`, sc.join("\n"));

