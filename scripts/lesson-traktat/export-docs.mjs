mp.push("арабские тексты; ссылки на другие трактаты «Рисале-и Нур»; рассуждение о софистах (67:18–68:43).");
mp.push("Неразборчивых мест, на которые опирается фильм, нет; сомнительные распознавания имён не использованы.", "");
SCENES.forEach((s, i) => {
  const ts = tl.scenes[i];
  mp.push(`## Сцена ${i + 1} (${mmss(ts.from)} в фильме). ${s.title}`, "");
  mp.push(`Интервалы записи: ${s.src.map((r) => `**${r}**`).join(", ")}`);
  if (s.srcNote) mp.push(`Примечание: ${s.srcNote}`);
  mp.push("");
  for (const r of s.src) {
    if (r === "урок") {
      mp.push("> Повторение уже рассказанного в фильме или представление ведущего; новых утверждений нет.", "");
      continue;
    }
    const [a, b] = r.split("–").map(toSec);
    const segs = tr.segments.filter((g) => g.end > a + 0.5 && g.start < b - 0.5);
    mp.push(`> [${r}] ${segs.map((g) => g.text).join(" ")}`, "");
  }
});
writeFileSync(`${DIR}/source_map.md`, mp.join("\n"));
