// Числа, записанные в книге словами («более двадцати раз», «пять тысяч фунтов»), —
// для проверки, что каждое число реплики действительно стоит в указанных строках.
const UNITS = [
  [/^(одиннадцат)/, 11], [/^(двенадцат)/, 12], [/^(тринадцат)/, 13], [/^(четырнадцат)/, 14], [/^(пятнадцат)/, 15],
  [/^(шестнадцат)/, 16], [/^(семнадцат)/, 17], [/^(восемнадцат)/, 18], [/^(девятнадцат)/, 19],
  [/^(двадцат)/, 20], [/^(тридцат)/, 30], [/^(сорок)/, 40], [/^(пятьдесят|пятидесят)/, 50], [/^(шестьдесят|шестидесят)/, 60],
  [/^(семьдесят|семидесят)/, 70], [/^(восемьдесят|восьмидесят)/, 80], [/^(девяносто)/, 90], [/^(сто|ста)$/, 100],
  [/^(два|две|двух|двум)$/, 2], [/^(три|трех|трёх|трем|трём)$/, 3], [/^(четыре|четырех|четырёх)$/, 4], [/^(пять|пяти|пятью)$/, 5],
  [/^(шесть|шести)$/, 6], [/^(семь|семи)$/, 7], [/^(восемь|восьми)$/, 8], [/^(девять|девяти)$/, 9], [/^(десять|десяти)$/, 10],
];
const valueOf = (w) => {
  for (const [re, v] of UNITS) if (re.test(w)) return v;
  return null;
};
export const numbersInWords = (text) => {
  const out = new Set();
  const toks = text.toLowerCase().replace(/ё/g, "е").split(/[^а-я0-9]+/).filter(Boolean);
  for (let i = 0; i < toks.length; i++) {
    let v = valueOf(toks[i]);
    if (v === null) continue;
    let j = i + 1;
    // «двадцать пять»
    if (v >= 20 && v % 10 === 0 && j < toks.length) {
      const u = valueOf(toks[j]);
      if (u !== null && u < 10) {
        v += u;
        j++;
      }
    }
    out.add(v);
    if (j < toks.length && /^тысяч/.test(toks[j])) out.add(v * 1000);
  }
  return out;
};
