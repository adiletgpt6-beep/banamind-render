import { writeFileSync } from "node:fs";
import { SECTIONS } from "../../src/lesson-collins/theme.ts";
import { SCENES, timeline } from "./lib.mjs";

const tl = timeline();
const mmss = (s) => `${Math.floor(s / 60)}:${String(Math.floor(s % 60)).padStart(2, "0")}`;
const CH = { cold: "Два маховика: главный вопрос", study: "Как искали ответ: 1435 → 11 компаний", lead: "Лидер 5 уровня: скромность и воля", who: "Сначала кто, затем что", facts: "Суровые факты и парадокс Стокдейла", hedge: "Ёж, лиса и три круга", disc: "Культура дисциплины", tech: "Технологии как ускоритель", fly: "Маховик и порочный круг", end: "Двигатель прорыва: итоги и границы" };
const chapters = [];
SCENES.forEach((s, i) => {
  if (!chapters.length || chapters[chapters.length - 1].part !== s.part) chapters.push({ part: s.part, t: i === 0 ? 0 : tl.scenes[i].from, title: CH[s.part] });
});
const titles = [
  { n: 1, title: "Почему хорошие результаты мешают прорыву", thumb: "ХОРОШЕГО МАЛО" },
  { n: 2, title: "Команда, которая справится со сменой курса: сначала люди", thumb: "СНАЧАЛА ЛЮДИ" },
  { n: 3, title: "Три круга, которые помогают выбрать направление", thumb: "ТРИ КРУГА" },
  { n: 4, title: "Почему один большой рывок редко решает всё", thumb: "НЕ ОДИН РЫВОК", fav: true },
  { n: 5, title: "Как перестать начинать заново: маховик против порочного круга", thumb: "СНОВА С НУЛЯ?" },
];
const desc = `Почему похожие усилия дают такой разный результат? Банан BanaMind разбирает исследование Джима Коллинза «От хорошего к великому» (книга 2001 года; данные 1965–2000 гг.): как исследователи из 1435 компаний отобрали 11, сравнили их с похожими компаниями тех же лет и что отличало тех, кто совершил прорыв.

Три узла «двигателя прорыва»: люди (руководитель 5 уровня, «сначала кто»), ясность (суровые факты, парадокс Стокдейла, три круга) и последовательность (культура дисциплины, технологии как ускоритель, маховик против порочного круга). Все цифры — из книги и относятся к указанным в ней периодам; «великие» — термин исследования, а не оценка компаний сегодня. Исследование описывает 11 американских публичных компаний и не гарантирует результат в любой ситуации.

Главы:
${chapters.map((c) => `${mmss(c.t)} ${c.title}`).join("\n")}

Это оригинальный объясняющий фильм канала BanaMind, а не пересказ или аудиокнига.`;
writeFileSync(
  "books/good-to-great-collins/metadata/YOUTUBE_TITLES.md",
  `# BM-037 · пять названий

| № | Название | Надпись обложки |
|---|---|---|
${titles.map((t) => `| ${t.n} | ${t.title}${t.fav ? " **— МОЙ ФАВОРИТ**" : ""} | «${t.thumb}» (thumbnail-0${t.n}.jpg) |`).join("\n")}

**МОЙ ФАВОРИТ — №4 «Почему один большой рывок редко решает всё».** Это прямой ответ на главный вопрос фильма и его центральная метафора (маховик); название честное — не обещает быстрого успеха, а объясняет механизм, и стоит в паре с самой контрастной обложкой «НЕ ОДИН РЫВОК». Остальные варианты подходят для отдельных акцентов: №1 — парадокс «хорошее — враг великого», №2 — люди, №3 — три круга, №5 — эмоция порочного круга. Имя автора и название книги — в описании, а не в витрине. Окончательный выбор — за владельцем канала.

## Описание (черновик)

${desc}
`,
);
