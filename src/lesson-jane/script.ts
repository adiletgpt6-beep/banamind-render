const S = (id: string, text: string, pose?: PoseName, mood?: MoodName, extra: Partial<Line> = {}): Line => {
  const s = say(extra.say ?? text);
  return L(id, text, pose, mood, s === text ? extra : { ...extra, say: s });
};
const Q = (id: string, text: string, pose: PoseName = "ask"): Line => {
  const s = say(text);
  return { id, text, pose, mood: "think", wait: 5, ...(s === text ? {} : { say: s }) };
};

