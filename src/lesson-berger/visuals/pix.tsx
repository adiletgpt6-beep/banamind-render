// Точечные картинки BM-038: узнаваемый предмет собирается из плотных чётких
// цветных точек. Предмет описан слоями векторных контуров (SVG-path в локальных
// координатах ≈ −100…100); точки шестиугольной сетки берут цвет верхнего слоя,
// внутри которого лежат. Проверка «внутри» — штатный Path2D браузера рендера
// (isPointInPath / isPointInStroke), результат кэшируется: одинаковые точки в
// каждом кадре, без мерцания и без случайности.
import { hash, type Pt } from "./dots";

export type Layer = {
  d: string; // контур
  c: string | string[]; // цвет (или палитра — детерминированное смешение)
  w?: number; // если задано — это линия такой толщины (stroke), а не заливка
  rule?: "nonzero" | "evenodd";
};

let ctx: CanvasRenderingContext2D | null = null;
const getCtx = () => {
  if (!ctx) ctx = document.createElement("canvas").getContext("2d");
  return ctx!;
};

const cache = new Map<string, { x: number; y: number; c: string }[]>();

// точки картинки в локальных координатах (без масштаба и сдвига)
export const sampleLayers = (key: string, layers: Layer[], step: number, box = 110): { x: number; y: number; c: string }[] => {
  const ck = `${key}|${step}|${box}`;
  const hit = cache.get(ck);
  if (hit) return hit;
  const c = getCtx();
  const paths = layers.map((l) => new Path2D(l.d));
  const out: { x: number; y: number; c: string }[] = [];
  const rowH = step * 0.866;
  let j = 0;
  let n = 0;
  for (let y = -box; y <= box; y += rowH, j++)
    for (let x = -box + (j % 2 ? step / 2 : 0); x <= box; x += step) {
      for (let li = layers.length - 1; li >= 0; li--) {
        const L = layers[li];
        let inside = false;
        if (L.w) {
          c.lineWidth = L.w;
          c.lineCap = "round";
          c.lineJoin = "round";
          inside = c.isPointInStroke(paths[li], x, y);
        } else inside = c.isPointInPath(paths[li], x, y, L.rule ?? "nonzero");
        if (inside) {
          const col = Array.isArray(L.c) ? L.c[Math.floor(hash(n, 5 + li) * L.c.length)] : L.c;
          out.push({ x, y, c: col });
          n++;
          break;
        }
      }
    }
  cache.set(ck, out);
  return out;
};

// картинка в кадре: центр (cx, cy), размер s (1 → ±100 px), шаг сетки step (px на экране)
export const pic = (key: string, layers: Layer[], cx: number, cy: number, s: number, step = 11): Pt[] =>
  sampleLayers(key, layers, step / s).map((p) => ({ x: cx + p.x * s, y: cy + p.y * s, c: p.c }));

// ── библиотека предметов фильма (собственные условные рисунки, без логотипов) ──
