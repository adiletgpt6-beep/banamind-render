// Произношение имён для синтеза (ударения); текст титров остаётся обычным.
const say = (s: string) =>
  s
    .replace(/Дарси/g, "Да́рси")
    .replace(/Уикхем/g, "У́икхем")
    .replace(/Бингли/g, "Би́нгли")
    .replace(/Беннет/g, "Бе́ннет")
    .replace(/Лонгборн/g, "Ло́нгборн")
    .replace(/Пемберли/g, "Пе́мберли")
    .replace(/Гардинер/g, "Га́рдинер")
    .replace(/Шарлотт/g, "Шарло́тт")
    .replace(/Коллинз/g, "Ко́ллинз")
    .replace(/Остин/g, "О́стин")
    .replace(/Незерфилд/g, "Не́зерфилд")
    .replace(/Хансфорд/g, "Ха́нсфорд")
    .replace(/Джорджиан/g, "Джорджиа́н")
    .replace(/BanaMind/g, "Банама́йнд");
const S = (id: string, text: string, pose?: PoseName, mood?: MoodName, extra: Partial<Line> = {}): Line => {
  const s = say(extra.say ?? text);
  return L(id, text, pose, mood, s === text ? extra : { ...extra, say: s });
};

