// BalaGo-50, выпуск №34 / BG-034 — «10 толук сапар» («Пакет на 10 поездок»;
// композиция BalaGoBG034, 2D, 1080×1920, 30 fps, ≈ 70–85 с).
//
// Приём: анимация десяти отдельных бумажных билетов-конвертов (без
// календаря). Хук: большая «10» переворачивается в «?», над билетами висит
// штамп и не опускается, пока мама не разберётся. Один билет раскрывается
// двусторонним: лицо «ҮЙ → МЕКТЕП», оборот «МЕКТЕП → ҮЙ», компостер
// пробивает его насквозь — 1 билет = 1 толук сапар. Десять билетов веером
// получают ровно десять печатей «ТОЛУК САПАР» (не 9 + 1, без 11-го билета).
// На обороте — линейка без чисел: цена за ребёнка по расстоянию мектеп ↔ үй.
// Стопка лежит под прозрачной плашкой «Чечимге чейин төлөм жок», пока
// идут шаги топ → акысыз сыноо → чечим; после решения мамы плашка
// снимается, пакет оплачивается заранее. Верхний билет превращается в
// финальную карточку.
//
// Причинная ось: вопрос мамы «10 = ?» → что такое 1 сапар → 10 = 10, бонуса
// нет, это минимальный пакет → цена по расстоянию → порядок (сначала группа
// и бесплатная проба, решение за мамой, затем предоплата) → BalaGo в
// Бишкеке → CTA.
//
// Сценарий: campaigns/balago-50/episodes/34-BG-034.md (утверждён владельцем
// 15.10.2026). Точечные правки текста по фактам сайта (adiletzainidinov/BalaGo
// @469fbdc) и грамматике описаны в PR и в handoffs/BG-034.md: «топтом» →
// «пакет» (термин сайта; убирает созвучие «топ/топтом»), «ар бир бала үчүн»,
// «туруктуу сапарларды баштоо үчүн эң аз пакет — он сапар», «алдын ала төлөйсүз», уточнение о проверке адреса.
