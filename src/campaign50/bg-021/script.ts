// Произносимые слова — так же, как их размечает скрипт синтеза
// (scripts/lib/ts2d-tts.mjs): по пробелам, только с буквами или цифрами.
export const spokenWords = (s: string): string[] =>
  s.split(/\s+/).filter((w) => [...w].some((ch) => /[\p{L}\p{N}]/u.test(ch)));
