// BalaGo-50, выпуск №40 / BG-040 «Убакыттын да баасы бар»
// (композиция BalaGoBG040). Внутренний смысл: «Время тоже имеет цену».
//
// Мама в офисе Бишкека готовит презентацию. На самом интересном месте
// работы ей нужно свернуть ноутбук и ехать за ребёнком: «жумуш — мектеп —
// жумуш». Цена не только в дороге, но и в том, чтобы остановить задачу и
// снова собрать внимание. Мама сама отмечает на листе, что это
// повторяется каждый день, сама ищет способ организовать школьный маршрут
// заранее, находит BalaGo, вносит адрес, школу и время и сама отправляет
// подготовленное сообщение в WhatsApp. Затем — честные условия (группа,
// полная проба, решение родителя) как условный пример и финал с CTA.
//
// Монтажный мотив: тактовый ритм часов, принтера и листов бумаги;
// минутная стрелка — сквозной переход между сценами. Без таблиц метрик и
// калькулятора денег, без обещаний экономии точных минут.
//
// Сцены не имеют фиксированной длины: их длительность считается по
// фактической озвучке (timing.ts) — речь никогда не ускоряется.
// Файл без зависимостей от Remotion: его читают Node-скрипты озвучки.

