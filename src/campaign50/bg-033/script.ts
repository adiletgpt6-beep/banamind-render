// BalaGo-50, выпуск №33 / BG-033 — «Алгач сынап көрүңүз»
// («Попробуйте до оплаты»; композиция BalaGoBG033, 2D, 1080×1920, 30 fps,
// ≈ 75–85 с).
//
// Приём: эмоциональный рассказ о выборе через пустой квадрат-чекбокс.
// Вечерний стол в Бишкеке: мама держит открытый кошелёк, ручка зависает над
// пустым квадратом у её рукописной заметки «Төлөйүнбү?» — и не ставит
// отметку. Она закрывает кошелёк, зачёркивает вопрос и пишет «Алгач сынап
// көрсө болобу?». Тот же жёлтый квадрат проходит через весь ролик:
//   • в сцене условий рядом появляется ярлык «акысыз», квадрат пуст;
//   • в сцене ожидания в нём течёт песок, камера «ныряет» в квадрат —
//     внутри условный квартал, где по очереди загораются дома подходящей
//     группы (маркер «Шарттуу мисал»);
//   • в пробный день контур квадрата рисуется как маршрут: утром
//     ҮЙ → МЕКТЕП, после уроков МЕКТЕП → ҮЙ — и замыкается, когда ребёнок
//     дома;
//   • в сцене выбора под ним два равных пустых квадрата «Улантам» /
//     «Улантпайм»; галочку за маму никто не ставит;
//   • в финале штрих так и не поставленной галочки вытягивается в жёлтую
//     стрелку к контактам.
//
// Причинная ось: сомнение «платить ли?» → мама сама ищет и находит правило
// первой полной пробы → честная задержка (сначала группа) → полный пробный
// день ҮЙ → МЕКТЕП → ҮЙ (условный пример) → решение и оплата только потом →
// BalaGo в Бишкеке → CTA.
//
