// Общая геометрия ключевых кадров BG-033 (px кадра 1080×1920). Сцены
// стыкуются совпадением формы: последний кадр сцены N и первый кадр сцены
// N+1 показывают один и тот же предмет в одном и том же месте.
//
//   hook → rule   : телефон крупно (PHONE), на экране карточка BalaGo
//   rule → wait   : карточка мамы крупно (CARD), квадрат пуст + «акысыз»
//   wait → trial  : большая жёлтая рамка-квадрат (FRAME_SQ), внутри светает
//   trial → choice: карточка крупно (CARD), квадрат замкнут, внутри пуст
//   choice → cta  : карточка крупно (CARD) с тремя пустыми квадратами
//
// Карточка рисуется одним общим компонентом PaperCard (art/props.tsx),
// поэтому выглядит одинаково во всех сценах.

// Карточка мамы (бумага) в крупном плане: левый верхний угол, ширина,
