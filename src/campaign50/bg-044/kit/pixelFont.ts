// Пиксельный шрифт BG-044 (собственный, без внешних файлов): прописная
// кириллица с кыргызскими Ң, Ө, Ү, цифры и знаки. Глиф — 7 строк основной
// высоты; у Й — 2 строки «шапки» (бреве), у Ң, Ц, Щ — 1 строка хвоста вниз.
// «#» — закрашенный пиксель, «.» — пусто. Ширина глифа — по длине строки.
// Строчные буквы приводятся к прописным (toUpperCase сохраняет ү/ө/ң).
export type Glyph = { readonly rows: readonly string[]; readonly top?: readonly string[]; readonly tail?: string };

const g = (rows: string, extra?: { top?: string; tail?: string }): Glyph => ({
  rows: rows.trim().split(/\s+/),
  ...(extra?.top ? { top: extra.top.trim().split(/\s+/) } : {}),
  ...(extra?.tail ? { tail: extra.tail } : {}),
});

