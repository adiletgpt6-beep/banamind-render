// Латинские буквы, совпадающие по виду с кириллицей.
const LATIN: Record<string, string> = { A: "А", B: "В", C: "С", E: "Е", H: "Н", K: "К", M: "М", O: "О", P: "Р", T: "Т", X: "Х", Y: "Ү" };

export const glyphOf = (ch: string): Glyph => {
  const u = ch.toUpperCase();
  return GLYPHS[u] ?? GLYPHS[LATIN[u] ?? ""] ?? GLYPHS["?"];
};

export const hasGlyph = (ch: string) => {
  const u = ch.toUpperCase();
  return Boolean(GLYPHS[u] ?? GLYPHS[LATIN[u] ?? ""]);
};

// Ширина строки в «пикселях» шрифта (между глифами — 1 пиксель).
export const pixelTextWidth = (text: string) => {
  const chars = [...text];
  return chars.reduce((w, ch, i) => w + glyphOf(ch).rows[0].length + (i < chars.length - 1 ? 1 : 0), 0);
};

// Высота: 2 строки шапки + 7 основных + 1 хвост.
export const PIXEL_TOP = 2;
export const PIXEL_ROWS = 7;
export const PIXEL_HEIGHT = PIXEL_TOP + PIXEL_ROWS + 1;
