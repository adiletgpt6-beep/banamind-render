const stress = (text: string) => {
  let s = text;
  for (const [a, b] of NAMES) s = s.split(a).join(b);
  return s === text ? undefined : s;
};

const L = (id: string, text: string, pose?: PoseName, mood?: MoodName, extra: Partial<Line> = {}): Line => {
  const say = stress(text);
  return { id, text, pose, mood, ...(say ? { say } : {}), ...extra };
};
const Q = (id: string, text: string, wait = 4.5, pose: PoseName = "ask"): Line => ({ id, text, pose, mood: "wonder", wait });

