const say = (text: string) => text.replace(/[А-ЯЁа-яё’]+/g, (w) => S[w] ?? w);
// реплика с особым произношением, если в ней есть слова из словаря
const V = (id: string, text: string, pose?: PoseName, mood?: MoodName, extra: Partial<Line> = {}): Line => {
  const s = say(text);
  return L(id, text, pose, mood, s === text ? extra : { ...extra, say: s });
};

