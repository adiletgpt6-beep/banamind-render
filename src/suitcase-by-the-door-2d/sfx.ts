// Звуковые события сцен фильма №36. Каждая сцена экспортирует функцию
// плана звука (tl) => Sd2Sfx[] с кадрами относительно начала сцены —
// из тех же констант, что и анимация, поэтому звук совпадает с действием.
// Набор звуков намеренно маленький: только тихие бытовые звуки, у каждого
// есть видимое действие. Шагов, свистов и ударов на склейках нет.
import type { Sd2Timeline } from "./timing";

export type Sd2SfxKind =
  | "folder-down" // папка мягко ложится на стол / в чемодан
  | "paper" // шорох листа / перелистывание
  | "zip" // короткая спокойная молния
  | "lid" // крышка чемодана мягко закрывается
  | "tap" // одно касание кнопки на телефоне
  | "notify" // тихий отклик экрана после отправки заявки
  | "door" // дверь открывается/закрывается (дом)
  | "car-door" // дверь машины закрывается
  | "belt" // щелчок ремня безопасности
  | "spoon" // прибор кладут на стол
  | "chair" // стул
  | "suitcase-set" // чемодан ставят на пол (колёса)
  | "call" // тихий сигнал видеозвонка
  | "room" // атмосфера комнаты (длинная, тихая)
  | "yard" // атмосфера школьного двора (длинная, тихая)
  | "hall" // тихий зал (длинная)
  | "car" // мягкий салон в движении (длинная)
  | "chime"; // лёгкий звук финального экрана

export type Sd2Sfx = {
  readonly at: number; // кадр сцены
  readonly kind: Sd2SfxKind;
  readonly volume?: number; // 0…1 (по умолчанию — значение набора)
  readonly dur?: number; // для длинных: секунды
};

export type Sd2SfxPlan = (tl: Sd2Timeline) => readonly Sd2Sfx[];
